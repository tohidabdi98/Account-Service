CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    lastname VARCHAR(100) NOT NULL,
    email VARCHAR_IGNORECASE(255) NOT NULL,
    password VARCHAR(255) NOT NULL
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS failed_attempts INT DEFAULT 0 NOT NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS locked BOOLEAN DEFAULT FALSE NOT NULL;

ALTER TABLE users ALTER COLUMN email VARCHAR_IGNORECASE(255);

CREATE UNIQUE INDEX IF NOT EXISTS users_email_idx ON users (email);

CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee VARCHAR_IGNORECASE(255) NOT NULL,
    period VARCHAR(7) NOT NULL,
    salary BIGINT NOT NULL CHECK (salary >= 0),
    CONSTRAINT payments_employee_period_unique UNIQUE (employee, period)
);

CREATE TABLE IF NOT EXISTS roles (
    name VARCHAR(50) PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id BIGINT NOT NULL,
    role VARCHAR(50) NOT NULL,
    PRIMARY KEY (user_id, role),
    CONSTRAINT user_roles_user_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT user_roles_role_fk FOREIGN KEY (role) REFERENCES roles(name)
);

CREATE TABLE IF NOT EXISTS security_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_date TIMESTAMP NOT NULL,
    action VARCHAR(50) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    object VARCHAR(500) NOT NULL,
    path VARCHAR(255) NOT NULL
);
